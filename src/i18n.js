// Tilni saqlash va olish
const getLang = () => localStorage.getItem("wb-lang") || "uz";
const setLang = (lang) => {
  localStorage.setItem("wb-lang", lang);
  window.dispatchEvent(new CustomEvent("wb-lang-change", { detail: lang }));
};

// t() — tarjima funksiyasi
const t = (key) => {
  const lang = getLang();
  return TRANSLATIONS[lang]?.[key] || TRANSLATIONS["uz"][key] || key;
};

